import type { PortableTextBlock } from '@portabletext/types';

export type SanityImageRef = {
	_type: 'image';
	asset?: { _ref: string; _type: 'reference' };
	hotspot?: { x: number; y: number; height: number; width: number };
	crop?: { top: number; bottom: number; left: number; right: number };
};

export type SanityFileRef = {
	_type: 'file';
	asset?: { _ref: string; _type: 'reference' };
};

/* Column span of a gallery item within the 12-column grid. `pair-large` and
   `pair-small` predate the grid — they are still accepted so existing Sanity
   content keeps rendering, and both resolve to a 6-column half. */
export type GalleryItemLayout =
	| 'full'
	| 'two-thirds'
	| 'large-half'
	| 'half'
	| 'small-half'
	| 'third'
	| 'pair-large'
	| 'pair-small';

export type GalleryItem = {
	_key: string;
	type: 'image' | 'svg' | 'video' | 'gif';
	image?: SanityImageRef;
	video?: SanityFileRef;
	/* SVG only, added by a page's server load: the file's markup, cleaned, for
	   rendering inline so its shapes can be animated. Absent → plain <img>. */
	svgMarkup?: string;
	layout: GalleryItemLayout;
	aspectRatio?: number;
	/* Video only: set the footage on a flat colour panel — 3:2 for a desktop
	   or browser recording, 3:4 for a phone recording. */
	frame?: GalleryItemFrame;
	/* Hex colour of that panel; the site's cream when unset. */
	frameColor?: string;
	caption?: string;
};

export type GalleryItemFrame = 'none' | 'landscape' | 'portrait';

export type InfoBlock = {
	_key: string;
	title: string;
	items: string[];
};

export type PlaylistTrack = {
	_key: string;
	title: string;
	artist: string;
	audio: SanityFileRef;
	/* Tempo, generated by scripts/measure-tempo.mjs (animations/beat.ts reads
	   it): the felt BPM, the first beat's time, every beat's time (which
	   follows a live track's drift where a fixed grid would not), and the
	   low hits — where a kick or a bass note lands, with how hard, 0–1 —
	   which is what the hover cursor ripples on. */
	bpm?: number;
	beatOffset?: number;
	beats?: number[];
	hitTimes?: number[];
	hitStrengths?: number[];
};

export type SiteSettings = {
	name: string;
	aboutContent?: PortableTextBlock[];
	contactEmail?: string;
	themeIconDefault?: SanityImageRef;
	themeIconAlt?: SanityImageRef;
	themeIconFooterDefault?: SanityImageRef;
	themeIconFooterAlt?: SanityImageRef;
	footerWordmark?: string;
	footerWordmarkAsset?: SanityImageRef;
	playlist?: PlaylistTrack[];
};

export type WorkProject = {
	_id: string;
	title: string;
	slug: { current: string };
	tagline?: string;
	description?: PortableTextBlock[];
	infoBlocks?: InfoBlock[];
	collaborators?: string[];
	instagramUrl?: string;
	websiteUrl?: string;
	thumbnailImage?: SanityImageRef;
	/* Plays in the /work card in place of the image; the image is its poster. */
	thumbnailVideo?: SanityFileRef;
	thumbnailRatio?: number;
	/* Animated GIF centred over the thumbnail media, sized as a % of the card. */
	thumbnailGif?: SanityImageRef;
	thumbnailGifWidth?: number;
	heroImage?: SanityImageRef;
	heroVideo?: SanityFileRef;
	heroVideoPoster?: SanityImageRef;
	heroAspectRatio?: number;
	heroLogo?: SanityImageRef;
	heroLogoPosition?:
		| 'top-left'
		| 'top-center'
		| 'top-right'
		| 'middle-left'
		| 'center'
		| 'middle-right'
		| 'bottom-left'
		| 'bottom-center'
		| 'bottom-right';
	heroLogoWidth?: number;
	/* Animated GIF centred over the hero media, sized as a % of the hero. */
	heroGif?: SanityImageRef;
	heroGifWidth?: number;
	galleryItems?: GalleryItem[];
	publishedAt?: string;
	orderRank?: string;
};

export type WorkProjectListItem = Pick<
	WorkProject,
	| '_id'
	| 'title'
	| 'slug'
	| 'thumbnailImage'
	| 'thumbnailVideo'
	| 'thumbnailRatio'
	| 'thumbnailGif'
	| 'thumbnailGifWidth'
	| 'infoBlocks'
>;

export type WorkProjectNeighbors = {
	prev: { slug: string; title: string } | null;
	next: { slug: string; title: string } | null;
};

export type PersonalGallery = {
	galleryItems?: GalleryItem[];
};
