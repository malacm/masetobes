import { defineType, defineField } from 'sanity';

export const playlistTrack = defineType({
	name: 'playlistTrack',
	title: 'Playlist Track',
	type: 'object',
	fields: [
		defineField({
			name: 'title',
			title: 'Title',
			type: 'string',
			validation: (rule) => rule.required()
		}),
		defineField({
			name: 'artist',
			title: 'Artist',
			type: 'string',
			validation: (rule) => rule.required()
		}),
		defineField({
			name: 'audio',
			title: 'Audio file',
			type: 'file',
			options: { accept: 'audio/*' },
			validation: (rule) => rule.required()
		}),
		defineField({
			name: 'bpm',
			title: 'Tempo (BPM)',
			description:
				'The felt pulse of the track — the hover cursor beats to it while the track plays. Measured by scripts/measure-tempo.mjs; correct it here if the pulse is off.',
			type: 'number',
			validation: (rule) => rule.min(30).max(300)
		}),
		defineField({
			name: 'beatOffset',
			title: 'First beat (seconds)',
			description: 'How far into the file the first beat lands. Nudge it if the pulse is early or late.',
			type: 'number',
			validation: (rule) => rule.min(0)
		}),
		defineField({
			name: 'beats',
			title: 'Beat map',
			description: 'Every beat in seconds, generated by scripts/measure-tempo.mjs. Hidden: edit the tempo and first beat above instead.',
			type: 'array',
			of: [{ type: 'number' }],
			hidden: true
		}),
		defineField({
			name: 'hitTimes',
			title: 'Low hits (seconds)',
			description: 'Where a kick or bass note lands, generated by scripts/measure-tempo.mjs. The hover cursor ripples on these.',
			type: 'array',
			of: [{ type: 'number' }],
			hidden: true
		}),
		defineField({
			name: 'hitStrengths',
			title: 'Low hit strengths',
			description: 'How hard each low hit lands, 0–1, one per entry above.',
			type: 'array',
			of: [{ type: 'number' }],
			hidden: true
		})
	],
	preview: {
		select: { title: 'title', artist: 'artist' },
		prepare({ title, artist }) {
			return {
				title: title || 'Untitled track',
				subtitle: artist || ''
			};
		}
	}
});
